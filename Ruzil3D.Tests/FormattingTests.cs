		private static List<string> FindMismatches(string[,] cases, string culture, Func<double, string> format)
		{
			var mismatches = new List<string>();

			TestUtil.WithCulture(culture, () =>
			{
				for (var i = 0; i < cases.GetLength(0); i++)
				{
					var value = double.Parse(cases[i, 0], NumberStyles.Float, CultureInfo.InvariantCulture);
					var actual = format(value);
					if (actual != cases[i, 1])
					{
						mismatches.Add(cases[i, 0] + ": ожидалось \"" + cases[i, 1] + "\", получено \"" + actual + "\"");
					}
				}

				return mismatches;
			});

			return mismatches;
		}

		[Fact]
		public void DoubleToString_SameOutputAsBefore()
		{
			// Проверка констант ускорена отсевом заведомо неподходящих, и вывод не должен измениться.
			var mismatches = FindMismatches(InvariantCases, "", CStatic.DoubleToString);
			mismatches.AddRange(FindMismatches(RussianCases, "ru-RU", CStatic.DoubleToString));

			Assert.True(mismatches.Count == 0, string.Join(Environment.NewLine, mismatches));
		}

		[Fact]
		public void AngleToString_SameOutputAsBefore()
		{
			var mismatches = FindMismatches(AngleCases, "", CStatic.AngleToString);

			Assert.True(mismatches.Count == 0, string.Join(Environment.NewLine, mismatches));
		}

