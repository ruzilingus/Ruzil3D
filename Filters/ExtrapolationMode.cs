namespace Ruzil3D.Filters
{
    /// <summary>
    /// Режимы продолжения (экстраполяции) кривой или функции за пределы области определения.
    /// </summary>
    public enum ExtrapolationMode
    {
        /// <summary>
        /// Замкнутая кривая, продолжаемая периодически. <see cref="CurveInterpolationCompiler"/> замыкает ломаную отрезком
        /// от последней точки к первой, и период равен длине ломаной вместе с этим отрезком; у <see cref="InterpolationCompiler"/>
        /// период равен разности аргументов последней и первой точек.
        /// </summary>
        Closed,

        /// <summary>
        /// Кривая продолжается центральной симметрией (точечным отражением) относительно концевых точек, а не зеркальным
        /// отражением: для области определения [a, b] F(a − t) = 2F(a) − F(a + t) и F(b + t) = 2F(b) − F(b − t). Поэтому прямая
        /// продолжается той же прямой, а через каждые 2(b − a) кривая повторяется со сдвигом на 2(F(b) − F(a)).
        /// </summary>
        Mirror
    }
}