namespace Ruzil3D.Filters
{
    /// <summary>
    /// Представляет радиальное ядро сглаживающего фильтра: вес точки в зависимости от её расстояния до центра.
    /// Ядро должно стремиться к нулю, когда radius стремится к бесконечности.
    /// </summary>
    /// <remarks>
    /// Ядро вызывается только для radius ≥ 0 и должно возвращать конечные значения. Нормировать ядро не нужно: веса нормируются
    /// при компиляции (<see cref="BlurCompiler"/>, <see cref="SurfaceBlurFilter"/>). Отрицательные значения и нулевые участки
    /// допустимы, но сумма весов не должна быть равна нулю.
    /// </remarks>
    /// <param name="radius">Расстояние до центра фильтра, radius ≥ 0.</param>
    /// <returns>Значение ядра (вес).</returns>
    public delegate double BlurFunctionHandler(double radius);
}